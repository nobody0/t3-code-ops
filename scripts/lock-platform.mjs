import fs from 'node:fs';
import path from 'node:path';
import {atomicJson,digest,readJson,run,installRelease} from './lib/ko-release.mjs';
import {smoke} from './lib/ko-deployment.mjs';
const dir=path.resolve(process.argv[2]);
const platform=`${process.platform}-${process.arch}`;
const manifest=readJson(path.join(dir,'release.json'));
const lockDir=path.join(dir,'locks',platform);
fs.mkdirSync(lockDir,{recursive:true});
fs.copyFileSync(path.join(dir,manifest.artifact),path.join(lockDir,manifest.artifact));
atomicJson(path.join(lockDir,'package.json'),{private:true,dependencies:{t3:`file:${manifest.artifact}`}});
run('npm',['install','--package-lock-only','--ignore-scripts','--no-audit','--no-fund'],{cwd:lockDir,timeout:600000});
const files=['package.json','package-lock.json'];
const entry=Object.fromEntries(files.map(f=>[f,digest(path.join(lockDir,f))]));
fs.unlinkSync(path.join(lockDir,manifest.artifact));
atomicJson(path.join(lockDir,'receipt.json'),{platform,...entry});
atomicJson(path.join(dir,'release.json'),{...manifest,schemaVersion:2,platformLocks:{[platform]:entry}});
const installRoot=path.join(dir,'tested',platform);
const target=installRelease(dir,installRoot);
await smoke({node:process.execPath,root:installRoot},target);
fs.cpSync(lockDir,path.resolve('work/platform-locks',platform),{recursive:true});
console.log(`Locked install, native terminal and isolated startup passed: ${platform}`);
